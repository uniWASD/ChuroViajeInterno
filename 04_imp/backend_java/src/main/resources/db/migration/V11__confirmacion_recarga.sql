-- HU-12 (CU-05): confirmaciones de recarga de los conductores. 06_base_de_datos.md.
-- Las reglas las aplica ConfirmacionRecarga; estas restricciones son la segunda barrera.
-- No se guarda la ubicacion de la parada: solo sirve para comprobar la cercania (RN-05.13) en el momento.
CREATE TABLE confirmacion_recarga (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conductor_id BIGINT NOT NULL,
    surtidor_id BIGINT NOT NULL,
    tipo_codigo VARCHAR(32) NOT NULL,
    fecha TIMESTAMPTZ NOT NULL,
    -- Al borrar un conductor se borran sus confirmaciones.
    CONSTRAINT fk_confirmacion_recarga_conductor FOREIGN KEY (conductor_id)
        REFERENCES conductor (id) ON DELETE CASCADE,
    CONSTRAINT fk_confirmacion_recarga_surtidor FOREIGN KEY (surtidor_id)
        REFERENCES surtidor (id) ON DELETE CASCADE,
    CONSTRAINT fk_confirmacion_recarga_tipo FOREIGN KEY (tipo_codigo) REFERENCES tipo_combustible (codigo),
    -- RN-05.9: Desconocido no es una opcion al confirmar.
    CONSTRAINT ck_confirmacion_recarga_tipo CHECK (tipo_codigo <> 'DESCONOCIDO')
);

-- RN-05.14: la confirmacion repetida del mismo conductor, surtidor y tipo.
CREATE INDEX idx_confirmacion_recarga_repeticion ON confirmacion_recarga (conductor_id, surtidor_id, tipo_codigo, fecha);
-- P-21: la limpieza diaria borra las de mas de 30 dias (T-105).
CREATE INDEX idx_confirmacion_recarga_fecha ON confirmacion_recarga (fecha);
