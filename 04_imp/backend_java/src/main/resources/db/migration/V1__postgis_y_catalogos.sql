CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE tipo_evento (
    codigo VARCHAR(32) PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    color VARCHAR(7) NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    vigencia_minutos INTEGER NOT NULL CHECK (vigencia_minutos > 0),
    reportable BOOLEAN NOT NULL
);

CREATE TABLE tipo_combustible (
    codigo VARCHAR(32) PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE surtidor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    ubicacion GEOGRAPHY(Point, 4326) NOT NULL
);

CREATE INDEX idx_surtidor_ubicacion ON surtidor USING GIST (ubicacion);

CREATE TABLE surtidor_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surtidor_id BIGINT NOT NULL,
    alias VARCHAR(120) NOT NULL UNIQUE,
    CONSTRAINT fk_surtidor_alias_surtidor FOREIGN KEY (surtidor_id)
        REFERENCES surtidor (id) ON DELETE CASCADE,
    CONSTRAINT ck_surtidor_alias_normalizado CHECK (alias ~ '^[a-z0-9]+( [a-z0-9]+)*$')
);

CREATE INDEX idx_surtidor_alias_surtidor ON surtidor_alias (surtidor_id);

