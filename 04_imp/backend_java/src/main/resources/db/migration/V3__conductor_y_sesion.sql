-- HU-10 (CU-08): conductores y sesiones. 06_base_de_datos.md.
-- RN-08.4: un solo conductor por cuenta de Google (segunda barrera, la primera es el dominio).
-- RN-08.6: solo se guarda el identificador de la cuenta de Google, nunca sus credenciales ni su correo.
CREATE TABLE conductor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_id VARCHAR(255) NOT NULL,
    fecha_alta TIMESTAMPTZ NOT NULL,
    simulado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_conductor_google_id UNIQUE (google_id)
);

-- RN-08.12 / RN-08.14: el token de renovacion vale hasta su expiracion y se invalida al cerrar sesion.
-- Se guarda solo su huella SHA-256 (64 caracteres hexadecimales, validados por la restriccion): quien lea la base no puede usarlo.
CREATE TABLE sesion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conductor_id BIGINT NOT NULL,
    token_renovacion_hash VARCHAR(64) NOT NULL,
    emitida_en TIMESTAMPTZ NOT NULL,
    expira_en TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_sesion_token_renovacion_hash UNIQUE (token_renovacion_hash),
    CONSTRAINT fk_sesion_conductor FOREIGN KEY (conductor_id)
        REFERENCES conductor (id) ON DELETE CASCADE,
    CONSTRAINT ck_sesion_hash_hexadecimal CHECK (token_renovacion_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sesion_expiracion CHECK (expira_en > emitida_en)
);

CREATE INDEX idx_sesion_conductor ON sesion (conductor_id);
CREATE INDEX idx_sesion_expira_en ON sesion (expira_en);
