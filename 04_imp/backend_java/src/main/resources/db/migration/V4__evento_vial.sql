-- HU-01 (CU-01): eventos viales. 06_base_de_datos.md.
-- La ubicacion es un punto PostGIS; el reportante queda vacio en los eventos de telemetria.
-- Las reglas las aplica EventoVial; estas restricciones son la segunda barrera.
CREATE TABLE evento_vial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_codigo VARCHAR(32) NOT NULL,
    ubicacion GEOGRAPHY(Point, 4326) NOT NULL,
    ocurrio_en TIMESTAMPTZ NOT NULL,
    registrado_en TIMESTAMPTZ NOT NULL,
    reportante_id BIGINT,
    origen VARCHAR(16) NOT NULL,
    nivel VARCHAR(20),
    estado VARCHAR(16) NOT NULL,
    votos_real INTEGER NOT NULL DEFAULT 0,
    votos_falso INTEGER NOT NULL DEFAULT 0,
    simulado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_evento_vial_tipo FOREIGN KEY (tipo_codigo) REFERENCES tipo_evento (codigo),
    -- Al borrar un conductor (por ejemplo, uno simulado) se borran sus eventos (RN-07.8).
    CONSTRAINT fk_evento_vial_reportante FOREIGN KEY (reportante_id)
        REFERENCES conductor (id) ON DELETE CASCADE,
    CONSTRAINT ck_evento_vial_origen CHECK (origen IN ('CONDUCTOR', 'TELEMETRIA')),
    -- RN-01.12: el reportante existe solo en los eventos de conductor, y nunca sale en una respuesta.
    CONSTRAINT ck_evento_vial_reportante CHECK ((origen = 'CONDUCTOR') = (reportante_id IS NOT NULL)),
    CONSTRAINT ck_evento_vial_estado CHECK (estado IN ('ACTIVO', 'CONFIRMADO', 'RETIRADO', 'VENCIDO')),
    -- El nivel solo existe en la congestion.
    CONSTRAINT ck_evento_vial_nivel CHECK (
        (tipo_codigo = 'CONGESTION' AND nivel IN ('CONGESTIONADO', 'MUY_CONGESTIONADO'))
        OR (tipo_codigo <> 'CONGESTION' AND nivel IS NULL)),
    CONSTRAINT ck_evento_vial_votos CHECK (votos_real >= 0 AND votos_falso >= 0),
    CONSTRAINT ck_evento_vial_no_futuro CHECK (ocurrio_en <= registrado_en)
);

CREATE INDEX idx_evento_vial_ubicacion ON evento_vial USING GIST (ubicacion);
-- RN-01.8 y RN-01.9: duplicados y limite de reportes de un conductor.
CREATE INDEX idx_evento_vial_reportante ON evento_vial (reportante_id, registrado_en);
-- CU-02: la consulta de eventos vigentes.
CREATE INDEX idx_evento_vial_estado ON evento_vial (estado, ocurrio_en);
