-- HU-11 (CU-02): votos «real» o «falso» sobre los eventos. 06_base_de_datos.md.
CREATE TABLE voto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL,
    conductor_id BIGINT NOT NULL,
    valor VARCHAR(8) NOT NULL,
    fecha TIMESTAMPTZ NOT NULL,
    simulado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_voto_evento FOREIGN KEY (evento_id) REFERENCES evento_vial (id) ON DELETE CASCADE,
    CONSTRAINT fk_voto_conductor FOREIGN KEY (conductor_id) REFERENCES conductor (id) ON DELETE CASCADE,
    CONSTRAINT ck_voto_valor CHECK (valor IN ('REAL', 'FALSO')),
    -- RN-02.11: un solo voto por conductor y evento (segunda barrera, la primera es el servicio).
    CONSTRAINT uq_voto_evento_conductor UNIQUE (evento_id, conductor_id)
);

CREATE INDEX idx_voto_conductor ON voto (conductor_id);
