-- HU-08 (CU-06) y CU-05, CU-09: estado de combustible por surtidor, tipo y origen. 06_base_de_datos.md.
-- Las reglas las aplica EstadoCombustible; estas restricciones son la segunda barrera.
CREATE TABLE estado_combustible (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surtidor_id BIGINT NOT NULL,
    tipo_codigo VARCHAR(32) NOT NULL,
    origen VARCHAR(16) NOT NULL,
    disponible BOOLEAN NOT NULL,
    fila VARCHAR(16),
    -- La fecha del dato: la del mensaje (RN-06.16), la de la confirmacion (RN-05.11) o el updated_at de ANH (RN-09.13).
    fecha_dato TIMESTAMPTZ NOT NULL,
    -- Solo ANH (RN-09.12, RN-09.13): el saldo y el estado tal como llegan, y cuando lo leyo el backend (RN-09.17).
    litros NUMERIC(12, 2),
    estado_anh VARCHAR(8),
    consultado_en TIMESTAMPTZ,
    actualizado_en TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_estado_combustible_surtidor FOREIGN KEY (surtidor_id)
        REFERENCES surtidor (id) ON DELETE CASCADE,
    CONSTRAINT fk_estado_combustible_tipo FOREIGN KEY (tipo_codigo) REFERENCES tipo_combustible (codigo),
    CONSTRAINT ck_estado_combustible_origen CHECK (origen IN ('WHATSAPP', 'CONDUCTORES', 'ANH')),
    -- P-15
    CONSTRAINT ck_estado_combustible_fila CHECK (fila IS NULL OR fila IN ('SIN_FILA', 'CORTA', 'MEDIA', 'LARGA')),
    -- RN-09.7
    CONSTRAINT ck_estado_combustible_litros CHECK (litros IS NULL OR litros >= 0),
    CONSTRAINT ck_estado_combustible_estado_anh CHECK (estado_anh IS NULL OR estado_anh IN ('ALTO', 'MEDIO', 'BAJO')),
    -- Los litros, el estado de ANH y el momento de la lectura son solo de ANH; un dato de ANH siempre sabe cuando se leyo.
    CONSTRAINT ck_estado_combustible_solo_anh CHECK (
        (origen = 'ANH' AND consultado_en IS NOT NULL)
        OR (origen <> 'ANH' AND litros IS NULL AND estado_anh IS NULL AND consultado_en IS NULL)),
    -- RN-05.3, RN-06.17: un solo estado por surtidor, tipo y origen; el nuevo reemplaza al anterior si es mas reciente.
    CONSTRAINT uq_estado_combustible UNIQUE (surtidor_id, tipo_codigo, origen)
);

CREATE INDEX idx_estado_combustible_surtidor ON estado_combustible (surtidor_id);
